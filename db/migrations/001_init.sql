-- menhu-cms 初始表结构（PostgreSQL 17）
-- 迁移文件按文件名顺序执行，每个文件一个事务，执行记录在 schema_migrations 中，只执行一次。
-- 已上线的迁移文件不要修改，需要改表结构请新增 002_xxx.sql。

-- 站点设置：单行 JSON，字段与 SiteSettings 一致
CREATE TABLE settings (
  id   smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  data jsonb    NOT NULL DEFAULT '{}'
);

CREATE TABLE channels (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug        text    NOT NULL UNIQUE,
  name        text    NOT NULL,
  description text    NOT NULL DEFAULT '',
  keywords    text    NOT NULL DEFAULT '',
  sort        integer NOT NULL DEFAULT 99,
  show_in_nav boolean NOT NULL DEFAULT true,
  icon        text
);

CREATE TABLE articles (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id   integer     NOT NULL REFERENCES channels (id) ON DELETE RESTRICT,
  title        text        NOT NULL,
  short_title  text,
  summary      text        NOT NULL DEFAULT '',
  content      text        NOT NULL DEFAULT '',
  cover        text,
  author       text        NOT NULL DEFAULT '',
  source       text        NOT NULL DEFAULT '',
  tags         text[]      NOT NULL DEFAULT '{}',
  is_headline  boolean     NOT NULL DEFAULT false,
  is_focus     boolean     NOT NULL DEFAULT false,
  status       text        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  views        integer     NOT NULL DEFAULT 0,
  published_at timestamptz NOT NULL DEFAULT now(),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  -- 菜谱结构化信息（RecipeInfo），普通文章为 NULL
  recipe       jsonb
);

-- 前台列表：最新 / 频道分页 / 上下篇
CREATE INDEX articles_published_idx ON articles (published_at DESC, id DESC) WHERE status = 'published';
CREATE INDEX articles_channel_published_idx ON articles (channel_id, published_at DESC, id DESC) WHERE status = 'published';
-- 热门排行
CREATE INDEX articles_views_idx ON articles (views DESC) WHERE status = 'published';
-- 标签页 / 相关推荐（tags @> / && 查询）
CREATE INDEX articles_tags_idx ON articles USING gin (tags);
-- 后台列表、外键删除检查
CREATE INDEX articles_channel_idx ON articles (channel_id, id DESC);

/*
 * 从旧版 db.json（或 db/seed.json）导入数据。
 *   replace = false：库里已有数据时拒绝导入（防止误覆盖）
 *   replace = true ：清空后重新导入（仅用于 JSON → PostgreSQL 切换时的最终同步）
 * 保留原有 id，并把自增序列推进到 max(id, 旧 seq)，已删除文章的 id 不会被复用。
 */
CREATE FUNCTION import_menhu_json(doc jsonb, replace boolean DEFAULT false) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
  n_channels int;
  n_articles int;
  max_ch int;
  max_ar int;
BEGIN
  IF replace THEN
    TRUNCATE articles, channels, settings RESTART IDENTITY;
  ELSIF EXISTS (SELECT 1 FROM settings) OR EXISTS (SELECT 1 FROM channels) THEN
    RAISE EXCEPTION '数据库中已有数据，拒绝导入';
  END IF;

  INSERT INTO settings (id, data) VALUES (1, COALESCE(doc -> 'settings', '{}'));

  INSERT INTO channels (id, slug, name, description, keywords, sort, show_in_nav, icon)
  SELECT c.id, c.slug, c.name, COALESCE(c.description, ''), COALESCE(c.keywords, ''),
         COALESCE(c.sort, 99), COALESCE(c."showInNav", true), NULLIF(c.icon, '')
  FROM jsonb_to_recordset(COALESCE(doc -> 'channels', '[]')) AS c (
    id int, slug text, name text, description text, keywords text, sort int, "showInNav" boolean, icon text
  );
  GET DIAGNOSTICS n_channels = ROW_COUNT;

  INSERT INTO articles (id, channel_id, title, short_title, summary, content, cover, author, source, tags,
                        is_headline, is_focus, status, views, published_at, created_at, updated_at, recipe)
  SELECT a.id, a."channelId", a.title, NULLIF(a."shortTitle", ''), COALESCE(a.summary, ''), COALESCE(a.content, ''),
         NULLIF(a.cover, ''), COALESCE(a.author, ''), COALESCE(a.source, ''),
         ARRAY(SELECT jsonb_array_elements_text(COALESCE(a.tags, '[]'))),
         COALESCE(a."isHeadline", false), COALESCE(a."isFocus", false), COALESCE(a.status, 'draft'), COALESCE(a.views, 0),
         COALESCE(a."publishedAt", now()), COALESCE(a."createdAt", a."publishedAt", now()),
         COALESCE(a."updatedAt", a."publishedAt", now()), NULLIF(a.recipe, 'null')
  FROM jsonb_to_recordset(COALESCE(doc -> 'articles', '[]')) AS a (
    id int, "channelId" int, title text, "shortTitle" text, summary text, content text, cover text, author text,
    source text, tags jsonb, "isHeadline" boolean, "isFocus" boolean, status text, views int,
    "publishedAt" timestamptz, "createdAt" timestamptz, "updatedAt" timestamptz, recipe jsonb
  );
  GET DIAGNOSTICS n_articles = ROW_COUNT;

  max_ch := GREATEST(COALESCE((doc -> 'seq' ->> 'channel')::int, 0), COALESCE((SELECT max(id) FROM channels), 0));
  max_ar := GREATEST(COALESCE((doc -> 'seq' ->> 'article')::int, 0), COALESCE((SELECT max(id) FROM articles), 0));
  PERFORM setval(pg_get_serial_sequence('channels', 'id'), GREATEST(max_ch, 1), max_ch >= 1);
  PERFORM setval(pg_get_serial_sequence('articles', 'id'), GREATEST(max_ar, 1), max_ar >= 1);

  RETURN format('导入完成：%s 个频道，%s 篇文章', n_channels, n_articles);
END;
$$;
